const menuButton = document.querySelector('.menu-toggle');
const navigation = document.querySelector('#primary-nav');
const languageButton = document.querySelector('#language-toggle');
const themeButton = document.querySelector('#theme-toggle');
const root = document.documentElement;

function readPreference(key, fallback) {
  try {
    return localStorage.getItem(key) || fallback;
  } catch {
    return fallback;
  }
}

function savePreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // The controls still work for this page view when storage is unavailable.
  }
}

let currentLanguage = readPreference('abdasha-language', 'ar');
let currentTheme = readPreference('abdasha-theme', 'light');
if (!messages[currentLanguage]) currentLanguage = 'ar';
if (!['light', 'dark'].includes(currentTheme)) currentTheme = 'light';

function closeMenu() {
  if (!menuButton || !navigation) return;
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', messages[currentLanguage]['menu.open']);
  navigation.classList.remove('is-open');
}

function applyLanguage(language) {
  currentLanguage = messages[language] ? language : 'ar';
  const text = messages[currentLanguage];
  root.lang = currentLanguage;
  root.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = text[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    const value = text[element.dataset.i18nContent];
    if (value !== undefined) element.setAttribute('content', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = text[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute('alt', value);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = text[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });

  if (languageButton) {
    languageButton.textContent = currentLanguage === 'ar' ? 'EN' : 'عربي';
    languageButton.setAttribute('aria-label', text['controls.language']);
    languageButton.setAttribute('title', text['controls.language']);
  }
  if (themeButton) {
    const themeLabel = currentTheme === 'dark' ? text['controls.themeLight'] : text['controls.themeDark'];
    themeButton.setAttribute('aria-label', themeLabel);
    themeButton.setAttribute('title', themeLabel);
  }
  if (menuButton && menuButton.getAttribute('aria-expanded') === 'true') {
    menuButton.setAttribute('aria-label', text['menu.close']);
  }

  document.querySelectorAll('[data-wa-key][data-wa-phone]').forEach((link) => {
    const message = text[`wa.${link.dataset.waKey}`];
    if (message) {
      link.href = `https://wa.me/${link.dataset.waPhone}?text=${encodeURIComponent(message)}`;
    }
  });

  savePreference('abdasha-language', currentLanguage);
}

function applyTheme(theme) {
  currentTheme = theme === 'dark' ? 'dark' : 'light';
  root.dataset.theme = currentTheme;
  const text = messages[currentLanguage];
  if (themeButton) {
    const label = currentTheme === 'dark' ? text['controls.themeLight'] : text['controls.themeDark'];
    themeButton.setAttribute('aria-label', label);
    themeButton.setAttribute('title', label);
  }
  const themeColor = document.querySelector('meta[name="theme-color"]');
  if (themeColor) themeColor.setAttribute('content', currentTheme === 'dark' ? '#11191b' : '#17434a');
  savePreference('abdasha-theme', currentTheme);
}

languageButton?.addEventListener('click', () => {
  applyLanguage(currentLanguage === 'ar' ? 'en' : 'ar');
  closeMenu();
});

themeButton?.addEventListener('click', () => {
  applyTheme(currentTheme === 'light' ? 'dark' : 'light');
});

if (menuButton && navigation) {
  menuButton.addEventListener('click', () => {
    const open = menuButton.getAttribute('aria-expanded') !== 'true';
    menuButton.setAttribute('aria-expanded', String(open));
    menuButton.setAttribute('aria-label', messages[currentLanguage][open ? 'menu.close' : 'menu.open']);
    navigation.classList.toggle('is-open', open);
  });

  navigation.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeMenu();
  });
  document.addEventListener('click', (event) => {
    if (!navigation.contains(event.target) && !menuButton.contains(event.target)) closeMenu();
  });

  const desktopQuery = window.matchMedia('(min-width: 681px)');
  if (desktopQuery.addEventListener) desktopQuery.addEventListener('change', closeMenu);
  else desktopQuery.addListener(closeMenu);
}

applyLanguage(currentLanguage);
applyTheme(currentTheme);
